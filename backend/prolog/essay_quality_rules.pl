% Loader for the modular essay quality rules.

:- prolog_load_context(directory, Dir),
   directory_file_path(Dir, rules, RulesDir),
   directory_file_path(RulesDir, 'text_utils.pl', TextUtils),
   directory_file_path(RulesDir, 'argument_rules.pl', ArgumentRules),
   directory_file_path(RulesDir, 'coherence_rules.pl', CoherenceRules),
   directory_file_path(RulesDir, 'redundancy_rules.pl', RedundancyRules),
   directory_file_path(RulesDir, 'vocabulary_rules.pl', VocabularyRules),
   directory_file_path(RulesDir, 'sentence_rules.pl', SentenceRules),
   directory_file_path(RulesDir, 'intro_conclusion_rules.pl', IntroConclusionRules),
   directory_file_path(RulesDir, 'logic_rules.pl', LogicRules),
   directory_file_path(RulesDir, 'fact_rules.pl', FactRules),
   directory_file_path(RulesDir, 'essay_quality_aggregation.pl', AggregationRules),
   ensure_loaded(TextUtils),
   ensure_loaded(ArgumentRules),
   ensure_loaded(CoherenceRules),
   ensure_loaded(RedundancyRules),
   ensure_loaded(VocabularyRules),
   ensure_loaded(SentenceRules),
   ensure_loaded(IntroConclusionRules),
   ensure_loaded(LogicRules),
   ensure_loaded(FactRules),
   ensure_loaded(AggregationRules).
